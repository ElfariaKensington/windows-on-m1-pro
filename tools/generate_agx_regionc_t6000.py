#!/usr/bin/env python3
"""Emit the J316s/T6000 RegionC word table and config-snapshot expectations.

Same method as the J313 table in drivers/apple-agx/shared/src/apple_agx_regionc.c:
the pinned proxyclient G13/V13_5 InitData_RegionC builder over the live ADT,
sparse non-zero 32-bit words, FNV-1a64 oracle over the words-only image.
"""
import argparse
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "m1n1_windows" / "proxyclient"))
import generate_agx_hwdata_profile as base  # noqa: E402
import generate_agx_hwdata_profile_t6000 as t6000  # noqa: E402

SCALARS = [
    "gpu-avg-power-filter-tc-ms", "gpu-avg-power-ki-only",
    "gpu-avg-power-kp", "gpu-avg-power-min-duty-cycle",
    "gpu-avg-power-target-filter-tc", "gpu-fast-die0-integral-gain",
    "gpu-fast-die0-prop-tgt-delta", "gpu-fast-die0-proportional-gain",
    "gpu-fast-die0-release-temp", "gpu-perf-boost-ce-step",
    "gpu-perf-boost-min-util", "gpu-perf-filter-drop-threshold",
    "gpu-perf-filter-time-constant", "gpu-perf-filter-time-constant2",
    "gpu-perf-integral-gain", "gpu-perf-integral-gain2",
    "gpu-perf-integral-min-clamp", "gpu-perf-proportional-gain",
    "gpu-perf-proportional-gain2", "gpu-perf-reset-iters",
    "gpu-perf-tgt-utilization", "gpu-ppm-filter-time-constant-ms",
    "gpu-ppm-ki", "gpu-ppm-kp", "gpu-pwr-filter-time-constant",
    "gpu-pwr-integral-gain", "gpu-pwr-integral-min-clamp",
    "gpu-pwr-min-duty-cycle", "gpu-pwr-proportional-gain",
    "gpu-pwr-sample-period-aic-clks", "gpu-idle-off-delay-ms",
    "gpu-fender-idle-off-delay-ms", "gpu-fw-early-wake-timeout-ms",
]


def fnv(b):
    h = 0xcbf29ce484222325
    for x in b:
        h = ((h ^ x) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--adt", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    a = ap.parse_args()
    adt_bytes = a.adt.read_bytes()
    from m1n1.adt import load_adt
    from m1n1.agx.initdata import CHIP_INFO
    from m1n1.constructutils import Ver
    from m1n1.fw.agx.initdata import InitData_RegionC
    adt = load_adt(adt_bytes)
    Ver.set_version_key("V", "V13_5")
    Ver.set_version_key("G", "G13")
    raw = base.raw_properties(adt_bytes, "/arm-io/sgx")
    count = struct.unpack("<I", raw["perf-state-count"])[0]
    tables = struct.unpack("<I", raw["perf-state-table-count"])[0]
    core = t6000.perf_table(raw["perf-states"], count, tables)
    sram = t6000.perf_table(raw["perf-states-sram"], count, tables)
    info = CHIP_INFO[0x6000]
    pwr = t6000.calc_power_t600x(core, sram, info.unk_3cf4[:tables], info.unk_3d14[:tables],
                                 [8] * tables)
    info.max_power = max(pwr) // 1000
    info.rel_max_powers = [p // 1000 * 100 // info.max_power for p in pwr]
    rc = InitData_RegionC(adt["/arm-io/sgx"], info)
    data = rc.build()
    if len(data) != 0x12394:
        raise SystemExit(f"RegionC size {len(data):#x} != 0x12394")
    words = [(o, struct.unpack_from("<I", data, o)[0]) for o in range(0, len(data), 4)
             if struct.unpack_from("<I", data, o)[0]]
    img = bytearray(len(data))
    for o, v in words:
        struct.pack_into("<I", img, o, v)
    if bytes(img) != data:
        raise SystemExit("RegionC has non-word-aligned content")
    presence, bits = 0, []
    for i, n in enumerate(SCALARS):
        v = raw.get(n)
        if v is not None and len(v) >= 4:
            presence |= 1 << i
            bits.append(struct.unpack_from("<I", v)[0])
        else:
            bits.append(0)
    freqs = [core[0][i][0] for i in range(count)]
    volts = [core[0][i][1] for i in range(count)]
    base_ps = struct.unpack("<I", raw["gpu-perf-base-pstate"])[0]
    max_ps = struct.unpack("<I", raw["gpu-num-perf-states"])[0]
    period = struct.unpack("<I", raw["gpu-power-sample-period"])[0]
    region = struct.unpack("<Q", raw["gpu-region-base"])[0]
    out = ["/* Generated by tools/generate_agx_regionc_t6000.py from the J316s 13.5 ADT; do not edit. */",
           "#define APPLE_AGX_REGIONC_T6000_SCALAR_PRESENCE 0x%xULL" % presence,
           "#define APPLE_AGX_REGIONC_T6000_ORACLE_FNV1A64 0x%016xULL" % fnv(img),
           "#define APPLE_AGX_REGIONC_T6000_PERF_STATE_COUNT %uu" % count,
           "#define APPLE_AGX_REGIONC_T6000_PERF_TABLE_COUNT %uu" % tables,
           "#define APPLE_AGX_REGIONC_T6000_BASE_PSTATE %uu" % base_ps,
           "#define APPLE_AGX_REGIONC_T6000_MAX_PSTATE %uu" % max_ps,
           "#define APPLE_AGX_REGIONC_T6000_SAMPLE_PERIOD_MS %uu" % period,
           "#define APPLE_AGX_REGIONC_T6000_GPU_REGION_BASE 0x%xULL" % region,
           "static const APPLE_AGX_REGIONC_WORD AppleAgxRegionCT6000Words[] = {"]
    out += ["    {0x%05xu, 0x%08xu}," % w for w in words]
    out += ["};",
            "static const unsigned int AppleAgxRegionCT6000Frequencies[%u] = {%s};" %
            (count, ", ".join("%uu" % f for f in freqs)),
            "static const unsigned int AppleAgxRegionCT6000Voltages[%u] = {%s};" %
            (count, ", ".join("%uu" % v for v in volts)),
            "static const unsigned int AppleAgxRegionCT6000Scalars[APPLE_AGX_CONFIG_SCALAR_COUNT] = {%s};" %
            ", ".join("0x%08xu" % b for b in bits), ""]
    a.output.write_text("\n".join(out))
    print(f"RegionC: {len(words)} words, oracle {fnv(img):#x}, presence {presence:#x}")


if __name__ == "__main__":
    main()
