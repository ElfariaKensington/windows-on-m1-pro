#!/usr/bin/env python3
"""Generate the J316s (T6000) AGX G2 contract headers from config/j316s-agx.json.

The live values come from the J316s-GPU-001 boot log (stub macOS 13.5 iBoot ADT).
The J313 renderers are reused unchanged so every consumer keeps the same
J313_AGX_G2_* / HV_AGX_G2_* macro names; only the values and the 42-bit UAT output
width differ.  The J313 headers include these when APPLE_AGX_PLATFORM_J316S /
HV_AGX_PLATFORM_J316S is defined.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate_j313_agx_g2_contract as j313  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config" / "j316s-agx.json"
OUTPUTS = {
    "windows": ROOT / "drivers/apple-agx/shared/include/j316s_agx_g2.generated.h",
    "m1n1": ROOT / "m1n1_windows/src/hv_agx_g2_j316s.generated.h",
}
GUEST_INTERRUPTS = tuple(range(880, 889))
POWER_BROKER = (0x300000000, 0x1000)


def load():
    data = json.loads(CONFIG.read_text())
    if data["platform"] != "J316s" or data["soc"] != "T6000":
        raise SystemExit("config is not the J316s/T6000 contract")
    if (data["firmware"]["generation"], data["firmware"]["version"]) != ("G13", "V13_5"):
        raise SystemExit("J316s contract must carry the 13.5 G13 firmware ABI")
    if data["uat"] != {"page_size": 0x4000, "num_contexts": 64, "address_bits": 42}:
        raise SystemExit("T6000 UAT must be 16 KiB pages, 64 contexts, 42-bit output")
    r = {k: (v["base"], v["size"]) for k, v in data["regions"].items()}
    physical = tuple(data["interrupts"])
    if len(physical) != 9:
        raise SystemExit("expected 5 SGX and 4 ASC interrupts")
    sha = hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()
    lifecycle = j313.FirmwareLifecycle(**j313.FIRMWARE_LIFECYCLE_EXACT)
    asc_base, asc_size = r["asc_mmio"]
    sgx_base, sgx_size = r["sgx_mmio"]
    if not (sgx_base <= asc_base and asc_base + asc_size <= sgx_base + sgx_size):
        raise SystemExit("ASC must sit inside the SGX ACPI aperture")
    return j313.G2Contract(
        contract_version=3,
        platform="J316s",
        acpi_hid="APPL0002",
        source_contract_sha256=sha,
        acpi_mmio=(("sgx_mmio", sgx_base, sgx_size), ("gpu", *r["gpu"])),
        mmio_subregions=(("asc_mmio", asc_base, asc_size),),
        synthetic_mmio=(("power_broker", *POWER_BROKER),),
        firmware_regions=tuple((n, *r[n]) for n in j313.EXACT_FIRMWARE_REGIONS),
        interrupt_routes=tuple(j313.InterruptRoute(physical=p, guest=g)
                               for p, g in zip(physical, GUEST_INTERRUPTS)),
        context_id=63, queue_index=1, work_timeout_ms=500,
        page_size=0x4000, address_bits=42, num_contexts=64,
        firmware_generation="G13", firmware_version="V13_5",
        firmware_lifecycle=lifecycle,
    ), data


def render(contract, data):
    original = j313._validate_windows_binary_contract

    def validate(c):  # identical checks, 42-bit UAT output for T6000
        object.__setattr__(c, "address_bits", 40)
        try:
            original(c)
        finally:
            object.__setattr__(c, "address_bits", 42)

    j313._validate_windows_binary_contract = validate
    try:
        win = j313.render_windows_header(contract)
    finally:
        j313._validate_windows_binary_contract = original
    m1n1 = j313.render_m1n1_header(contract)
    tag = "/* J316s/T6000 values from config/j316s-agx.json; generated by tools/generate_j316s_agx_g2_contract.py. */\n"
    extra_win = ["", "/* J316s additions */",
                 "#define J313_AGX_G2_PLATFORM_J316S 1u",
                 f"#define J313_AGX_G2_HANDOFF_PA 0x{data['regions']['handoff']['base']:x}ULL",
                 f"#define J313_AGX_G2_PHYSICAL_LIMIT (1ULL << {data['uat']['address_bits']})",
                 f"#define J313_AGX_G2_NUM_CORES {data['gpu_config']['num_cores']}u",
                 f"#define J313_AGX_G2_NUM_CLUSTERS {data['gpu_config']['num_clusters']}u", ""]
    win = tag + win.replace("#endif /* J313_AGX_G2_GENERATED_H */",
                            "\n".join(extra_win) + "\n#endif /* J313_AGX_G2_GENERATED_H */")
    seg = data["stage2_passthrough"]
    extra_m1n1 = ["/* J316s additions: exact stage-2 passthrough windows inside the ACPI SGX aperture */",
                  "#define HV_AGX_G2_PLATFORM_J316S 1u",
                  f"#define HV_AGX_G2_PHYSICAL_LIMIT (1ULL << {data['uat']['address_bits']})",
                  f"#define HV_AGX_G2_PASSTHROUGH_COUNT {len(seg)}u",
                  "#define HV_AGX_G2_PASSTHROUGH_VALUES {" + ", ".join(
                      f"{{0x{s['base']:x}ULL, 0x{s['size']:x}ULL}}" for s in seg) + "}",
                  f"#define HV_AGX_G2_GFX_PS_REG 0x{data['power']['ps_reg']:x}ULL", ""]
    m1n1 = tag + m1n1.replace("/* clang-format on */",
                              "\n".join(extra_m1n1) + "/* clang-format on */")
    for line in j313.PLATFORM_PROLOGUE_WINDOWS:
        win = win.replace(line + "\n", "", 1)
    for line in j313.PLATFORM_PROLOGUE_M1N1:
        m1n1 = m1n1.replace(line + "\n", "", 1)
    return {"windows": win, "m1n1": m1n1}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    contract, data = load()
    out = render(contract, data)
    stale = [k for k, p in OUTPUTS.items() if not p.exists() or p.read_text() != out[k]]
    if a.check:
        if stale:
            ap.error("stale: " + ", ".join(stale))
        return
    for k in stale:
        OUTPUTS[k].write_text(out[k])
    print("J316s contract sha256", contract.source_contract_sha256)


if __name__ == "__main__":
    main()
